"""Export routes — CSV, JSON, Markdown, PDF."""

import csv
import io
import json
from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import Response
from fastapi.templating import Jinja2Templates
from jinja2 import Environment, FileSystemLoader
from sqlalchemy.orm import Session

from app.database import get_session
from app.models import Scan

router = APIRouter(prefix="/api/export", tags=["export"])
templates = Jinja2Templates(directory="app/templates")


@router.get("/{scan_id}/csv")
def export_csv(scan_id: int, db: Session = Depends(get_session)):
    scan = db.query(Scan).filter(Scan.id == scan_id).first()
    if not scan:
        raise HTTPException(status_code=404, detail="Scan not found")

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["source", "target", "data_type", "value", "extra", "detected_at"])
    for r in scan.results:
        writer.writerow([r.source, r.target, r.data_type, r.value, r.extra, str(r.detected_at)])

    output.seek(0)
    return Response(
        content=output.getvalue(),
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename={scan.domain}_scan_{scan_id}.csv"},
    )


@router.get("/{scan_id}/json")
def export_json(scan_id: int, db: Session = Depends(get_session)):
    scan = db.query(Scan).filter(Scan.id == scan_id).first()
    if not scan:
        raise HTTPException(status_code=404, detail="Scan not found")

    data = {
        "scan_id": scan.id,
        "domain": scan.domain,
        "status": scan.status,
        "created_at": str(scan.created_at),
        "total_results": len(scan.results),
        "results": [
            {
                "source": r.source,
                "target": r.target,
                "data_type": r.data_type,
                "value": r.value,
                "extra": r.extra,
                "detected_at": str(r.detected_at),
            }
            for r in scan.results
        ],
    }

    return Response(
        content=json.dumps(data, indent=2),
        media_type="application/json",
        headers={"Content-Disposition": f"attachment; filename={scan.domain}_scan_{scan_id}.json"},
    )


@router.get("/{scan_id}/md")
def export_markdown(scan_id: int, db: Session = Depends(get_session)):
    scan = db.query(Scan).filter(Scan.id == scan_id).first()
    if not scan:
        raise HTTPException(status_code=404, detail="Scan not found")

    lines = [
        f"# OSINT Scan Report: {scan.domain}",
        "",
        f"- **Scan ID:** {scan.id}",
        f"- **Status:** {scan.status}",
        f"- **Date:** {scan.created_at}",
        f"- **Total Findings:** {len(scan.results)}",
        "",
        "## Results",
        "",
        "| Source | Type | Value |",
        "|--------|------|-------|",
    ]
    for r in scan.results:
        value_clean = r.value.replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {r.source} | {r.data_type} | {value_clean} |")

    lines.extend(["", "---", f"*Generated by OSINT Dashboard on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}*"])

    return Response(
        content="\n".join(lines),
        media_type="text/markdown",
        headers={"Content-Disposition": f"attachment; filename={scan.domain}_scan_{scan_id}.md"},
    )


@router.get("/{scan_id}/pdf")
def export_pdf(scan_id: int, db: Session = Depends(get_session)):
    """Generate styled PDF report via WeasyPrint."""
    from collections import Counter
    from weasyprint import HTML

    scan = db.query(Scan).filter(Scan.id == scan_id).first()
    if not scan:
        raise HTTPException(status_code=404, detail="Scan not found")

    results = scan.results
    results_by_source = dict(Counter(r.source for r in results).most_common())
    results_by_type = dict(Counter(r.data_type for r in results).most_common())

    env = Environment(loader=FileSystemLoader("app/templates"))
    template = env.get_template("scan_pdf.html")
    html_string = template.render(
        scan=scan,
        results=results,
        results_by_source=results_by_source,
        results_by_type=results_by_type,
        timestamp=datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
    )

    pdf_bytes = HTML(string=html_string).write_pdf(presentational_hints=True)
    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename={scan.domain}_scan_{scan_id}.pdf"},
    )
